// Combines all migrations into one file that can be pasted into the Supabase
// SQL Editor on a brand-new project: supabase/setup/all_migrations.sql
// Run: npm run db:bundle   (re-run after adding a migration)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const header = `-- =============================================================================
-- Chabad at Lehigh — complete database setup (generated by npm run db:bundle)
--
-- Paste this whole file into Supabase → SQL Editor → New query → Run,
-- ONCE, on a NEW project. It creates all tables, security rules and functions.
-- Do not edit by hand; edit supabase/migrations/* and regenerate.
-- Files included: ${files.join(", ")}
-- =============================================================================
`;

const body = files
  .map((f) => `\n-- >>>>>>>>>>>>>>>>>>>> ${f} <<<<<<<<<<<<<<<<<<<<\n\n${readFileSync(path.join(dir, f), "utf8").trim()}\n`)
  .join("\n");

mkdirSync(path.join(root, "supabase", "setup"), { recursive: true });
writeFileSync(path.join(root, "supabase", "setup", "all_migrations.sql"), header + body);
console.log(`Wrote supabase/setup/all_migrations.sql (${files.length} migrations)`);
